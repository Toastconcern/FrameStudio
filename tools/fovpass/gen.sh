#!/bin/sh
# Builds src/fov_spirv.h from fovpass.vert/.frag (run on a machine with glslc: the Steam Frame has it).
cd "$(dirname "$0")"
for s in vert frag; do glslc -O --target-env=vulkan1.1 -o fovpass.$s.spv fovpass.$s || exit 1; done
{
  echo "#pragma once"
  echo "// Generated by tools/fovpass/gen.sh from tools/fovpass/fovpass.vert / .frag: the smooth-foveation pass."
  echo "#include <cstdint>"
  for s in vert frag; do
    n=$( [ $s = vert ] && echo kFovPassVert || echo kFovPassFrag )
    echo "static const uint32_t ${n}[] = {"
    od -An -v -tx4 fovpass.$s.spv | sed 's/ *\([0-9a-f]\{8\}\)/0x\1u, /g'
    echo "};"
  done
} > ../../src/fov_spirv.h
