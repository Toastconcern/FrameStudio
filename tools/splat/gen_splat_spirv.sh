#!/bin/sh
# Regenerates src/splat_spirv.h from splat.vert / splat.frag. Needs glslc (the Frame has it in /usr/bin) or glslang
# (Khronos's release; set GLSLANG=/path/to/glslang).
set -e
cd "$(dirname "$0")"
if [ -n "$GLSLANG" ]; then
    "$GLSLANG" -V --target-env vulkan1.1 -Os splat.vert -o /tmp/splat.vert.spv
    "$GLSLANG" -V --target-env vulkan1.1 -Os splat.frag -o /tmp/splat.frag.spv
else
    glslc -O --target-env=vulkan1.1 -fshader-stage=vert splat.vert -o /tmp/splat.vert.spv
    glslc -O --target-env=vulkan1.1 -fshader-stage=frag splat.frag -o /tmp/splat.frag.spv
fi
python3 - /tmp/splat.vert.spv /tmp/splat.frag.spv > ../../src/splat_spirv.h <<'PY'
import struct, sys
print("#pragma once")
print("// GENERATED by tools/splat/gen_splat_spirv.sh from tools/splat/splat.{vert,frag}. Do not edit by hand.")
print("//   vert: set0 b0 Splats[] (32 bytes each), b1 order[], b2 Frame { mat4 clipFromWorld[2]; mat4 worldFromModel; vec4 viewport; }")
print("//         4 vertices a splat (triangle strip), one instance a splat; multiview")
print("//   frag: premultiplied colour (blend ONE, ONE_MINUS_SRC_ALPHA)")
print("#include <cstddef>\n#include <cstdint>\n")
for name, path in (("Vert", sys.argv[1]), ("Frag", sys.argv[2])):
    data = open(path, "rb").read()
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    print("static const uint32_t kSplat%sSpirv[] = {" % name)
    for i in range(0, len(words), 8):
        print("    " + ",".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    print("};")
    print("static const size_t kSplat%sSize = sizeof(kSplat%sSpirv);\n" % (name, name))
PY
